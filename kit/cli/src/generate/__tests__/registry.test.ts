import { test } from "@fast-check/vitest";
import fc from "fast-check";
import { describe, expect, it } from "vitest";
import { renderRegistry } from "../registry.js";

const base = {
  hasModuleTs: false,
  hasEnv: false,
  hasAuth: false,
  hasAuthClient: false,
  locales: [],
};

describe("renderRegistry", () => {
  it("emituje importy i tablice dla modułu z wszystkimi plikami", () => {
    const { server, client } = renderRegistry([
      {
        name: "demo",
        hasModuleTs: true,
        hasEnv: true,
        hasAuth: true,
        hasAuthClient: true,
        locales: ["pl", "en"],
      },
    ]);
    expect(
      server.startsWith(
        "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate\n",
      ),
    ).toBe(true);
    expect(server).toContain(
      'import demoModule from "@/features/demo/module";',
    );
    expect(server).toContain(
      'import { envSchema as demoEnvSchema } from "@/features/demo/env";',
    );
    expect(server).toContain(
      'import { authPlugin as demoAuthPlugin } from "@/features/demo/auth";',
    );
    expect(server).toContain("export const modules = [demoModule];");
    expect(server).toContain(
      '{ key: "demo", load: () => import("@/features/demo/i18n/pl.json").then((m) => m.default) }',
    );
    expect(server).toContain('import("@/features/demo/i18n/en.json")');
    expect(
      client.startsWith(
        "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate\n",
      ),
    ).toBe(true);
    expect(client).toContain(
      'import { authClientPlugin as demoAuthClientPlugin } from "@/features/demo/auth-client";',
    );
    expect(client).toContain(
      "export const authClientPlugins = [demoAuthClientPlugin];",
    );
    expect(client).toContain("export const clientModules = [demoModule];");
  });

  it("moduły bez plików dają puste tablice i puste locale", () => {
    const { server, client } = renderRegistry([{ name: "x", ...base }]);
    expect(server).toContain("export const modules: never[] = [];");
    expect(server).toContain("pl: [],");
    expect(client).toContain("export const clientModules: never[] = [];");
  });

  it("klient eksportuje pełne obiekty modułów, nie projekcję pól", () => {
    const { client } = renderRegistry([
      { name: "a", ...base, hasModuleTs: true },
      { name: "b", ...base, hasModuleTs: true },
    ]);
    expect(client).toContain(
      "export const clientModules = [aModule, bModule];",
    );
    expect(client).not.toContain("routePrefixes:");
  });

  it("nazwy z myślnikiem dają poprawne identyfikatory", () => {
    const { server } = renderRegistry([
      { name: "my-feature", ...base, hasModuleTs: true },
    ]);
    expect(server).toContain(
      'import myFeatureModule from "@/features/my-feature/module";',
    );
  });

  it("kolejność wejściowa jest zachowana", () => {
    const { server } = renderRegistry([
      { name: "b", ...base, hasModuleTs: true },
      { name: "a", ...base, hasModuleTs: true },
    ]);
    expect(server).toContain("export const modules = [bModule, aModule];");
  });
  const demo = {
    name: "demo",
    hasModuleTs: true,
    hasEnv: true,
    hasAuth: true,
    hasAuthClient: true,
    locales: ["pl", "en"],
  };

  it("serwer ma pełny kontrakt pliku dla modułu ze wszystkim", () => {
    expect(renderRegistry([demo]).server).toEqual(
      [
        "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate",
        'import demoModule from "@/features/demo/module";',
        'import { envSchema as demoEnvSchema } from "@/features/demo/env";',
        'import { authPlugin as demoAuthPlugin } from "@/features/demo/auth";',
        "",
        "export const modules = [demoModule];",
        "export const moduleEnvSchemas = [demoEnvSchema];",
        "export const authPlugins = [demoAuthPlugin];",
        "",
        "export type MessageLoader = { key: string; load: () => Promise<Record<string, unknown>> };",
        "",
        'export const moduleMessages: Record<"pl" | "en", MessageLoader[]> = {',
        "  pl: [",
        '    { key: "demo", load: () => import("@/features/demo/i18n/pl.json").then((m) => m.default) },',
        "  ],",
        "  en: [",
        '    { key: "demo", load: () => import("@/features/demo/i18n/en.json").then((m) => m.default) },',
        "  ],",
        "};",
        "",
      ].join("\n"),
    );
  });

  it("klient ma pełny kontrakt pliku dla modułu ze wszystkim", () => {
    expect(renderRegistry([demo]).client).toEqual(
      [
        "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate",
        'import { authClientPlugin as demoAuthClientPlugin } from "@/features/demo/auth-client";',
        'import demoModule from "@/features/demo/module";',
        "",
        "export const authClientPlugins = [demoAuthClientPlugin];",
        "export const clientModules = [demoModule];",
        "",
      ].join("\n"),
    );
  });

  it("moduł bez env, auth i auth-client nie trafia do tych importów i tablic", () => {
    const { server, client } = renderRegistry([
      demo,
      {
        name: "b",
        hasModuleTs: true,
        hasEnv: false,
        hasAuth: false,
        hasAuthClient: false,
        locales: [],
      },
    ]);
    expect(server).not.toContain("@/features/b/env");
    expect(server).not.toContain("@/features/b/auth");
    expect(server).toContain(
      "export const moduleEnvSchemas = [demoEnvSchema];",
    );
    expect(server).toContain("export const authPlugins = [demoAuthPlugin];");
    expect(server).toContain("export const modules = [demoModule, bModule];");
    expect(client).not.toContain("@/features/b/auth-client");
    expect(client).toContain(
      "export const authClientPlugins = [demoAuthClientPlugin];",
    );
    expect(client).toContain(
      "export const clientModules = [demoModule, bModule];",
    );
  });

  it("kolejne separatory w nazwie daje jeden człon camelCase", () => {
    const { server } = renderRegistry([
      { name: "my--mod", ...base, hasModuleTs: true },
    ]);
    expect(server).toContain(
      'import myModModule from "@/features/my--mod/module";',
    );
    expect(server).toContain("export const modules = [myModModule];");
  });

  test.prop([fc.stringMatching(/^[a-z][a-z0-9]*([-_.][a-z0-9]+)*$/)])(
    "identyfikator importu modułu zawiera tylko znaki alfanumeryczne",
    (name) => {
      const { server } = renderRegistry([{ name, ...base, hasModuleTs: true }]);
      const importLine = server.split("\n")[1] ?? "";
      expect(importLine).toMatch(/^import [A-Za-z0-9]+Module from "/);
    },
  );
});
