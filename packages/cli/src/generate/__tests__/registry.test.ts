import { describe, expect, it } from "vitest";
import { renderRegistry } from "../registry.js";

const base = {
  hasModuleTs: false,
  hasEnv: false,
  hasAuth: false,
  hasAuthClient: false,
  locales: [],
};

describe("renderRegistry", () => {
  it("emituje importy i tablice dla modułu z wszystkimi plikami", () => {
    const { server, client } = renderRegistry([
      {
        name: "demo",
        hasModuleTs: true,
        hasEnv: true,
        hasAuth: true,
        hasAuthClient: true,
        locales: ["pl", "en"],
      },
    ]);
    expect(
      server.startsWith(
        "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate\n",
      ),
    ).toBe(true);
    expect(server).toContain(
      'import demoModule from "@/features/demo/module";',
    );
    expect(server).toContain(
      'import { envSchema as demoEnvSchema } from "@/features/demo/env";',
    );
    expect(server).toContain(
      'import { authPlugin as demoAuthPlugin } from "@/features/demo/auth";',
    );
    expect(server).toContain("export const modules = [demoModule];");
    expect(server).toContain(
      '{ key: "demo", load: () => import("@/features/demo/i18n/pl.json").then((m) => m.default) }',
    );
    expect(server).toContain('import("@/features/demo/i18n/en.json")');
    expect(
      client.startsWith(
        "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate\n",
      ),
    ).toBe(true);
    expect(client).toContain(
      'import { authClientPlugin as demoAuthClientPlugin } from "@/features/demo/auth-client";',
    );
    expect(client).toContain(
      "export const authClientPlugins = [demoAuthClientPlugin];",
    );
    expect(client).toContain("export const clientModules = [demoModule];");
  });

  it("moduły bez plików dają puste tablice i puste locale", () => {
    const { server, client } = renderRegistry([{ name: "x", ...base }]);
    expect(server).toContain("export const modules: never[] = [];");
    expect(server).toContain("pl: [],");
    expect(client).toContain("export const clientModules: never[] = [];");
  });

  it("klient eksportuje pełne obiekty modułów, nie projekcję pól", () => {
    const { client } = renderRegistry([
      { name: "a", ...base, hasModuleTs: true },
      { name: "b", ...base, hasModuleTs: true },
    ]);
    expect(client).toContain(
      "export const clientModules = [aModule, bModule];",
    );
    expect(client).not.toContain("routePrefixes:");
  });

  it("nazwy z myślnikiem dają poprawne identyfikatory", () => {
    const { server } = renderRegistry([
      { name: "my-feature", ...base, hasModuleTs: true },
    ]);
    expect(server).toContain(
      'import myFeatureModule from "@/features/my-feature/module";',
    );
  });

  it("kolejność wejściowa jest zachowana", () => {
    const { server } = renderRegistry([
      { name: "b", ...base, hasModuleTs: true },
      { name: "a", ...base, hasModuleTs: true },
    ]);
    expect(server).toContain("export const modules = [bModule, aModule];");
  });
});
