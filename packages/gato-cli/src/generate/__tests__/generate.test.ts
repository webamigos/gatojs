import {
  cp,
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { generate } from "../index.js";

const fixturesDir = join(dirname(fileURLToPath(import.meta.url)), "fixtures");
const tmpDirs: string[] = [];

async function copyFixture(name: string): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "wa-generate-"));
  tmpDirs.push(dir);
  await cp(join(fixturesDir, name), dir, { recursive: true });
  return dir;
}

async function read(dir: string, path: string): Promise<string> {
  return readFile(join(dir, path), "utf8");
}

async function setState(
  dir: string,
  patch: Record<string, unknown>,
): Promise<void> {
  const path = join(dir, ".wa/kit.json");
  const state = JSON.parse(await readFile(path, "utf8"));
  await writeFile(path, JSON.stringify({ ...state, ...patch }, null, 2));
}

async function setDemoEnvExample(dir: string, example: string): Promise<void> {
  const path = join(dir, ".wa/kit.json");
  const state = JSON.parse(await readFile(path, "utf8"));
  state.modules.demo.manifest.env = [{ name: "DEMO_TOKEN", example }];
  await writeFile(path, JSON.stringify(state, null, 2));
}

async function addDemoEnglish(dir: string): Promise<void> {
  await mkdir(join(dir, "src/features/demo/i18n"), { recursive: true });
  await writeFile(
    join(dir, "src/features/demo/i18n/en.json"),
    '{ "title": "Demo" }',
  );
}

const HEADER =
  "// generated by GatoJS — do not edit. Run: npm run wa -- generate";

const NOTES_ENTRY = {
  manifest: {
    name: "notes",
    version: "0.1.0",
    description: "Notatki",
    requires: [],
    files: ["src/features/notes/**", "prisma/schema/notes.prisma"],
    dependencies: {},
    devDependencies: {},
    env: [{ name: "NOTES_LIMIT", example: "10" }],
    schemaRelations: [{ model: "Organization", field: "notes Note[]" }],
    compose: null,
    ciSteps: null,
    workspaces: [],
  },
};

async function addProjectModule(
  dir: string,
  name: string,
  entry: Record<string, unknown>,
): Promise<void> {
  const path = join(dir, ".wa/kit.json");
  const state = JSON.parse(await readFile(path, "utf8"));
  state.projectModules = { ...state.projectModules, [name]: entry };
  await writeFile(path, JSON.stringify(state, null, 2));
  await mkdir(join(dir, "src/features", name, "i18n"), { recursive: true });
  await writeFile(
    join(dir, "src/features", name, "module.ts"),
    "export default {};",
  );
  await writeFile(join(dir, "src/features", name, "i18n/pl.json"), "{}");
}

async function snapshotDir(dir: string): Promise<Record<string, string>> {
  const entries = await readdir(dir, { recursive: true });
  const snapshot: Record<string, string> = {};
  for (const entry of entries.sort()) {
    const full = join(dir, entry);
    if ((await stat(full)).isFile())
      snapshot[entry] = await readFile(full, "utf8");
  }
  return snapshot;
}

afterEach(async () => {
  await Promise.all(
    tmpDirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })),
  );
});

describe("generate", () => {
  it("generuje wszystkie cele", async () => {
    const dir = await copyFixture("minimal");
    const { changed } = await generate(dir);
    expect([...changed].sort()).toEqual([
      ".env.example",
      "docker-compose.yml",
      "prisma/schema/auth.prisma",
      "src/i18n/locales.generated.ts",
      "src/modules.client.generated.ts",
      "src/modules.generated.ts",
    ]);
    const reg = await read(dir, "src/modules.generated.ts");
    expect(reg).toContain('import demoModule from "@/features/demo/module"');
    expect(reg).toContain('import authModule from "@/features/auth/module"');
    expect(reg.startsWith("// generated by GatoJS — do not edit")).toBe(true);
    expect(reg.indexOf("authModule")).toBeLessThan(reg.indexOf("demoModule"));
    expect(await read(dir, "prisma/schema/auth.prisma")).toMatch(
      /wa:relations:start\n\s+demos Demo\[\]\n/,
    );
    expect(await read(dir, "prisma/schema/organizations.prisma")).toBe(
      await read(
        join(fixturesDir, "minimal"),
        "prisma/schema/organizations.prisma",
      ),
    );
    const env = await read(dir, ".env.example");
    expect(env).toContain("# demo\nDEMO_TOKEN=changeme");
    expect(env).not.toContain("# core");
    expect(await read(dir, "docker-compose.yml")).toContain(
      '# wa:services:start\n  demo:\n    image: demo:latest\n    ports:\n      - "9000:9000"\n  # wa:services:end',
    );
  });

  it("drugie uruchomienie nic nie zmienia", async () => {
    const dir = await copyFixture("minimal");
    await generate(dir);
    const snap = await snapshotDir(dir);
    expect((await generate(dir)).changed).toEqual([]);
    expect(await snapshotDir(dir)).toEqual(snap);
  });

  it("bez pola locales w kit.json plik języków ma pl i en", async () => {
    const dir = await copyFixture("minimal");
    await generate(dir);
    expect(await read(dir, "src/i18n/locales.generated.ts")).toBe(
      `${HEADER}\nexport const locales = ["pl", "en"] as const;\n`,
    );
  });

  it("locales [pl] → plik języków i moduleMessages tylko z pl", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { locales: ["pl"] });
    await generate(dir);
    expect(await read(dir, "src/i18n/locales.generated.ts")).toBe(
      `${HEADER}\nexport const locales = ["pl"] as const;\n`,
    );
    const reg = await read(dir, "src/modules.generated.ts");
    expect(reg).not.toMatch(/^\s+en:/m);
    expect(reg).not.toContain("en.json");
    expect(reg).toContain(
      "export const moduleMessages: Record<Locale, MessageLoader[]> = {\n  pl: [",
    );
    expect(reg).toContain('import("@/features/auth/i18n/pl.json")');
  });

  it("locales [pl, en] → rejestr z kluczem en i plik języków z oboma", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { locales: ["pl", "en"] });
    await generate(dir);
    expect(await read(dir, "src/i18n/locales.generated.ts")).toBe(
      `${HEADER}\nexport const locales = ["pl", "en"] as const;\n`,
    );
    const reg = await read(dir, "src/modules.generated.ts");
    expect(reg).toMatch(/^ {2}en: \[/m);
    expect(reg).toContain('import("@/features/auth/i18n/en.json")');
  });

  it("moduł z en.json przy locales [pl] → plik zostaje, loader en nie trafia do rejestru", async () => {
    const dir = await copyFixture("minimal");
    await addDemoEnglish(dir);
    await setState(dir, { locales: ["pl"] });
    await generate(dir);
    const reg = await read(dir, "src/modules.generated.ts");
    expect(reg).not.toContain("en.json");
    expect(reg).toContain('import("@/features/demo/i18n/pl.json")');
    expect(await read(dir, "src/features/demo/i18n/en.json")).toBe(
      '{ "title": "Demo" }',
    );
    expect(await read(dir, "src/features/auth/i18n/en.json")).toBe(
      '{ "title": "Sign in" }\n',
    );
  });

  it("zmiana locales z [pl] na [pl, en] przywraca loader en", async () => {
    const dir = await copyFixture("minimal");
    await addDemoEnglish(dir);
    await setState(dir, { locales: ["pl"] });
    await generate(dir);
    await setState(dir, { locales: ["pl", "en"] });
    const { changed } = await generate(dir);
    expect(changed).toContain("src/modules.generated.ts");
    expect(changed).toContain("src/i18n/locales.generated.ts");
    expect(await read(dir, "src/modules.generated.ts")).toContain(
      'import("@/features/demo/i18n/en.json")',
    );
  });

  it("{{projectSlug}} w przykładzie env podmieniony slugiem projektu", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { project: { name: "Acme Shop", slug: "acme-shop" } });
    await setDemoEnvExample(dir, "{{projectSlug}}_demo_{{projectSlug}}");
    await generate(dir);
    expect(await read(dir, ".env.example")).toContain(
      "# demo\nDEMO_TOKEN=acme-shop_demo_acme-shop\n",
    );
  });

  it("{{projectName}} w przykładzie env podmieniony nazwą projektu", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { project: { name: "Acme Shop", slug: "acme-shop" } });
    await setDemoEnvExample(dir, "{{projectName}}");
    await generate(dir);
    expect(await read(dir, ".env.example")).toContain(
      "# demo\nDEMO_TOKEN=Acme Shop\n",
    );
  });

  it("oba placeholdery w jednym przykładzie dostają właściwe wartości", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { project: { name: "Acme Shop", slug: "acme-shop" } });
    await setDemoEnvExample(
      dir,
      "{{projectName}}|{{projectSlug}}|{{projectName}}|{{projectSlug}}",
    );
    await generate(dir);
    expect(await read(dir, ".env.example")).toContain(
      "DEMO_TOKEN=Acme Shop|acme-shop|Acme Shop|acme-shop\n",
    );
  });

  it("przykład env bez placeholderów zostaje bez zmian", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { project: { name: "Acme Shop", slug: "acme-shop" } });
    await generate(dir);
    expect(await read(dir, ".env.example")).toContain(
      "# demo\nDEMO_TOKEN=changeme\n",
    );
  });

  it("placeholdery nie są podmieniane w przykładzie modułu core", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, { project: { name: "Acme Shop", slug: "acme-shop" } });
    await generate(dir);
    expect(await read(dir, ".env.example")).not.toContain("acme-shop");
  });

  it("drugie generate z locales [pl] i placeholderami → changed pusty", async () => {
    const dir = await copyFixture("minimal");
    await setState(dir, {
      locales: ["pl"],
      project: { name: "Acme Shop", slug: "acme-shop" },
    });
    await setDemoEnvExample(dir, "{{projectSlug}}_demo_{{projectSlug}}");
    await generate(dir);
    const snap = await snapshotDir(dir);
    expect((await generate(dir)).changed).toEqual([]);
    expect(await snapshotDir(dir)).toEqual(snap);
  });

  it("brak pliku docelowego (np. docker-compose.yml) → pominięty", async () => {
    const dir = await copyFixture("minimal");
    await rm(join(dir, "docker-compose.yml"));
    await expect(generate(dir)).resolves.toBeDefined();
    await expect(stat(join(dir, "docker-compose.yml"))).rejects.toThrow();
  });

  it("uszkodzony marker: błąd i żaden plik nie zmieniony", async () => {
    const dir = await copyFixture("broken-marker");
    const snap = await snapshotDir(dir);
    await expect(generate(dir)).rejects.toThrow(
      ".env.example: malformed region wa:modules",
    );
    expect(await snapshotDir(dir)).toEqual(snap);
  });
  it("modul projektu notes trafia do rejestrow serwerowego i klienckiego po modulach kitu", async () => {
    const dir = await copyFixture("minimal");
    await addProjectModule(dir, "notes", NOTES_ENTRY);
    await generate(dir);
    expect(await read(dir, "src/modules.generated.ts")).toBe(
      [
        HEADER,
        'import type { Locale } from "@/i18n/config";',
        'import { createEnv } from "@gatojs/env";',
        'import authModule from "@/features/auth/module";',
        'import demoModule from "@/features/demo/module";',
        'import notesModule from "@/features/notes/module";',
        'import { envSchema as demoEnvSchema } from "@/features/demo/env";',
        'import { authPlugin as authAuthPlugin } from "@/features/auth/auth";',
        "",
        "export const modules = [authModule, demoModule, notesModule];",
        "export const moduleEnvSchemas = [demoEnvSchema];",
        "export const authPlugins = [authAuthPlugin];",
        "export const auditSinks: never[] = [];",
        "export const env = createEnv(moduleEnvSchemas);",
        "",
        "export type MessageLoader = { key: string; load: () => Promise<Record<string, unknown>> };",
        "",
        "export const moduleMessages: Record<Locale, MessageLoader[]> = {",
        "  pl: [",
        '    { key: "auth", load: () => import("@/features/auth/i18n/pl.json").then((m) => m.default) },',
        '    { key: "demo", load: () => import("@/features/demo/i18n/pl.json").then((m) => m.default) },',
        '    { key: "notes", load: () => import("@/features/notes/i18n/pl.json").then((m) => m.default) },',
        "  ],",
        "  en: [",
        '    { key: "auth", load: () => import("@/features/auth/i18n/en.json").then((m) => m.default) },',
        "  ],",
        "};",
        "",
      ].join("\n"),
    );
    expect(await read(dir, "src/modules.client.generated.ts")).toBe(
      [
        HEADER,
        'import { authClientPlugin as authAuthClientPlugin } from "@/features/auth/auth-client";',
        'import authModule from "@/features/auth/module";',
        'import demoModule from "@/features/demo/module";',
        'import notesModule from "@/features/notes/module";',
        "",
        "export const authClientPlugins = [authAuthClientPlugin];",
        "export const clientModules = [authModule, demoModule, notesModule];",
        "",
      ].join("\n"),
    );
  });

  it("modul projektu dodaje env do regionu wa:modules i relacje do regionu wa:relations", async () => {
    const dir = await copyFixture("minimal");
    await addProjectModule(dir, "notes", NOTES_ENTRY);
    const { changed } = await generate(dir);
    expect(changed).toContain(".env.example");
    expect(changed).toContain("prisma/schema/organizations.prisma");
    expect(await read(dir, ".env.example")).toBe(
      "DATABASE_URL=x\n# wa:modules:start\n# demo\nDEMO_TOKEN=changeme\n\n# notes\nNOTES_LIMIT=10\n# wa:modules:end\n",
    );
    expect(await read(dir, "prisma/schema/organizations.prisma")).toBe(
      "model Organization {\n  id String @id\n  // wa:relations:start\n  notes Note[]\n  // wa:relations:end\n}\n",
    );
  });

  it("drugie generate z modulem projektu → changed pusty", async () => {
    const dir = await copyFixture("minimal");
    await addProjectModule(dir, "notes", NOTES_ENTRY);
    await generate(dir);
    const snap = await snapshotDir(dir);
    expect((await generate(dir)).changed).toEqual([]);
    expect(await snapshotDir(dir)).toEqual(snap);
  });

  it("modul kitu demo i modul projektu alfa: alfa po demo w obu rejestrach", async () => {
    const dir = await copyFixture("minimal");
    await addProjectModule(dir, "alfa", {
      manifest: {
        name: "alfa",
        version: "0.1.0",
        description: "Alfa",
        files: ["src/features/alfa/**"],
      },
    });
    await generate(dir);
    const server = await read(dir, "src/modules.generated.ts");
    expect(server).toContain(
      "export const modules = [authModule, demoModule, alfaModule];",
    );
    expect(server.indexOf("import demoModule from")).toBeLessThan(
      server.indexOf("import alfaModule from"),
    );
    expect(await read(dir, "src/modules.client.generated.ts")).toContain(
      "export const clientModules = [authModule, demoModule, alfaModule];",
    );
  });

  it("moduly projektu zeta i alfa trafiaja do rejestru alfabetycznie", async () => {
    const dir = await copyFixture("minimal");
    for (const name of ["zeta", "alfa"]) {
      await addProjectModule(dir, name, {
        manifest: {
          name,
          version: "0.1.0",
          description: name,
          files: [`src/features/${name}/**`],
        },
      });
    }
    await generate(dir);
    expect(await read(dir, "src/modules.client.generated.ts")).toContain(
      "export const clientModules = [authModule, demoModule, alfaModule, zetaModule];",
    );
  });

  it("modul projektu z niezainstalowanym wymogiem przerywa generowanie bez zmian plikow", async () => {
    const dir = await copyFixture("minimal");
    await addProjectModule(dir, "notes", {
      manifest: { ...NOTES_ENTRY.manifest, requires: ["uploads"] },
    });
    const snap = await snapshotDir(dir);
    await expect(generate(dir)).rejects.toThrow(
      "Project module notes requires a module that is not installed: uploads",
    );
    expect(await snapshotDir(dir)).toEqual(snap);
  });
});
