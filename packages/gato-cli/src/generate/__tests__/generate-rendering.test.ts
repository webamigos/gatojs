const tmpDirs: string[] = [];

type ModuleSpec = {
  version?: string;
  files?: string[];
  env?: { name: string; example: string }[];
  schemaRelations?: { model: string; field: string }[];
  compose?: string;
};

async function put(dir: string, path: string, content: string): Promise<void> {
  await mkdir(dirname(join(dir, path)), { recursive: true });
  await writeFile(join(dir, path), content);
}

async function makeProject(
  modules: Record<string, ModuleSpec>,
  locales: string[] = ["pl"],
): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "wa-rendering-"));
  tmpDirs.push(dir);
  const entries = Object.fromEntries(
    Object.entries(modules).map(([name, spec]) => [
      name,
      {
        version: spec.version ?? "1.0.0",
        manifest: {
          name,
          version: spec.version ?? "1.0.0",
          description: name,
          files: spec.files ?? [],
          env: spec.env ?? [],
          schemaRelations: spec.schemaRelations ?? [],
          compose: spec.compose ?? null,
        },
        files: {},
      },
    ]),
  );
  await put(
    dir,
    ".wa/kit.json",
    JSON.stringify({ kitVersion: "0.0.0", locales, modules: entries }),
  );
  await put(
    dir,
    "prisma/schema/auth.prisma",
    "// wa:relations:start\n// wa:relations:end\n",
  );
  await put(
    dir,
    "prisma/schema/organizations.prisma",
    "// wa:relations:start\n// wa:relations:end\n",
  );
  await put(dir, ".env.example", "A=1\n# wa:modules:start\n# wa:modules:end\n");
  await put(
    dir,
    "docker-compose.yml",
    "services:\n  # wa:services:start\n  # wa:services:end\n",
  );
  return dir;
}

async function read(dir: string, path: string): Promise<string> {
  return readFile(join(dir, path), "utf8");
}

async function snapshotDir(dir: string): Promise<Record<string, string>> {
  const entries = await readdir(dir, { recursive: true });
  const snapshot: Record<string, string> = {};
  for (const entry of entries.sort()) {
    const full = join(dir, entry);
    if ((await stat(full)).isFile())
      snapshot[entry] = await readFile(full, "utf8");
  }
  return snapshot;
}

