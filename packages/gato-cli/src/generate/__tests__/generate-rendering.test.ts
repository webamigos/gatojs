import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { generate } from "../index.js";

const tmpDirs: string[] = [];

type ModuleSpec = {
  files?: string[];
  env?: { name: string; example: string }[];
  schemaRelations?: { model: string; field: string }[];
  compose?: string;
};

async function put(dir: string, path: string, content: string): Promise<void> {
  await mkdir(dirname(join(dir, path)), { recursive: true });
  await writeFile(join(dir, path), content);
}

async function makeProject(
  modules: Record<string, ModuleSpec>,
  locales: string[] = ["pl"],
): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "wa-rendering-"));
  tmpDirs.push(dir);
  const entries = Object.fromEntries(
    Object.entries(modules).map(([name, spec]) => [
      name,
      {
        version: "1.0.0",
        manifest: {
          name,
          version: "1.0.0",
          description: name,
          files: spec.files ?? [],
          env: spec.env ?? [],
          schemaRelations: spec.schemaRelations ?? [],
          compose: spec.compose ?? null,
        },
        files: {},
      },
    ]),
  );
  await put(
    dir,
    ".wa/kit.json",
    JSON.stringify({ kitVersion: "0.0.0", locales, modules: entries }),
  );
  await put(
    dir,
    "prisma/schema/auth.prisma",
    "// wa:relations:start\n// wa:relations:end\n",
  );
  await put(
    dir,
    "prisma/schema/organizations.prisma",
    "// wa:relations:start\n// wa:relations:end\n",
  );
  await put(dir, ".env.example", "A=1\n# wa:modules:start\n# wa:modules:end\n");
  await put(
    dir,
    "docker-compose.yml",
    "services:\n  # wa:services:start\n  # wa:services:end\n",
  );
  return dir;
}

async function read(dir: string, path: string): Promise<string> {
  return readFile(join(dir, path), "utf8");
}

afterEach(async () => {
  await Promise.all(
    tmpDirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })),
  );
});

const HEADER =
  "// generated by wa — nie edytuj. Uruchom: npm run wa -- generate";

describe("generate: wykrywanie modułów w rejestrze", () => {
  it("moduł tylko z module.ts, tylko z env.ts i tylko z i18n/pl.json trafiają do rejestru", async () => {
    const dir = await makeProject({
      alpha: { files: ["src/features/alpha/**"] },
      beta: { files: ["src/features/beta/**"] },
      gamma: { files: ["src/features/gamma/**"] },
    });
    await put(dir, "src/features/alpha/module.ts", "export default {};");
    await put(dir, "src/features/beta/env.ts", "export const envSchema = {};");
    await put(dir, "src/features/gamma/i18n/pl.json", "{}");
    await generate(dir);
    expect(await read(dir, "src/modules.generated.ts")).toBe(
      [
        HEADER,
        'import type { Locale } from "@/i18n/config";',
        'import { createEnv } from "@gatojs/env";',
        'import alphaModule from "@/features/alpha/module";',
        'import { envSchema as betaEnvSchema } from "@/features/beta/env";',
        "",
        "export const modules = [alphaModule];",
        "export const moduleEnvSchemas = [betaEnvSchema];",
        "export const authPlugins: never[] = [];",
        "export const auditSinks: never[] = [];",
        "export const env = createEnv(moduleEnvSchemas);",
        "",
        "export type MessageLoader = { key: string; load: () => Promise<Record<string, unknown>> };",
        "",
        "export const moduleMessages: Record<Locale, MessageLoader[]> = {",
        "  pl: [",
        '    { key: "gamma", load: () => import("@/features/gamma/i18n/pl.json").then((m) => m.default) },',
        "  ],",
        "};",
        "",
      ].join("\n"),
    );
    expect(await read(dir, "src/modules.client.generated.ts")).toBe(
      [
        HEADER,
        'import alphaModule from "@/features/alpha/module";',
        "",
        "export const authClientPlugins: never[] = [];",
        "export const clientModules = [alphaModule];",
        "",
      ].join("\n"),
    );
  });

  it("moduł tylko z auth.ts i moduł tylko z auth-client.ts trafiają do rejestru", async () => {
    const dir = await makeProject({
      alpha: { files: ["src/features/alpha/**"] },
      beta: { files: ["src/features/beta/**"] },
    });
    await put(
      dir,
      "src/features/alpha/auth.ts",
      "export const authPlugin = {};",
    );
    await put(
      dir,
      "src/features/beta/auth-client.ts",
      "export const authClientPlugin = {};",
    );
    await generate(dir);
    expect(await read(dir, "src/modules.generated.ts")).toContain(
      'import { authPlugin as alphaAuthPlugin } from "@/features/alpha/auth";\n',
    );
    expect(await read(dir, "src/modules.client.generated.ts")).toContain(
      'import { authClientPlugin as betaAuthClientPlugin } from "@/features/beta/auth-client";\n',
    );
  });

  it("moduł tylko z audit-sink.ts trafia do auditSinks, a nie do klienta", async () => {
    const dir = await makeProject({
      alpha: { files: ["src/features/alpha/**"] },
      beta: { files: ["src/features/beta/**"] },
    });
    await put(
      dir,
      "src/features/alpha/audit-sink.ts",
      "export const auditSink = {};",
    );
    await put(dir, "src/features/beta/module.ts", "export default {};");
    await generate(dir);
    const server = await read(dir, "src/modules.generated.ts");
    expect(server).toContain(
      'import { auditSink as alphaAuditSink } from "@/features/alpha/audit-sink";\n',
    );
    expect(server).toContain("export const auditSinks = [alphaAuditSink];\n");
    expect(server).not.toContain("@/features/beta/audit-sink");
    expect(await read(dir, "src/modules.client.generated.ts")).not.toContain(
      "audit-sink",
    );
  });

  it("katalog bez żadnego rozpoznanego pliku nie trafia do rejestru", async () => {
    const dir = await makeProject({
      alpha: { files: ["src/features/alpha/**"] },
    });
    await put(dir, "src/features/alpha/readme.md", "x");
    await put(dir, "src/features/alpha/i18n/en.json", "{}");
    await generate(dir);
    expect(await read(dir, "src/modules.generated.ts")).toBe(
      [
        HEADER,
        'import type { Locale } from "@/i18n/config";',
        'import { createEnv } from "@gatojs/env";',
        "",
        "export const modules: never[] = [];",
        "export const moduleEnvSchemas: never[] = [];",
        "export const authPlugins: never[] = [];",
        "export const auditSinks: never[] = [];",
        "export const env = createEnv(moduleEnvSchemas);",
        "",
        "export type MessageLoader = { key: string; load: () => Promise<Record<string, unknown>> };",
        "",
        "export const moduleMessages: Record<Locale, MessageLoader[]> = {",
        "  pl: [],",
        "};",
        "",
      ].join("\n"),
    );
  });

  it("wzorce z wielu modułów: nazwy posortowane w obrębie modułu, każdy katalog raz", async () => {
    const dir = await makeProject({
      one: { files: ["src/features/zeta/**", "src/features/alpha/**"] },
      two: { files: ["src/features/alpha/**", "src/features/mid/**"] },
    });
    for (const name of ["zeta", "alpha", "mid"])
      await put(dir, `src/features/${name}/module.ts`, "export default {};");
    await generate(dir);
    expect(await read(dir, "src/modules.client.generated.ts")).toBe(
      [
        HEADER,
        'import alphaModule from "@/features/alpha/module";',
        'import zetaModule from "@/features/zeta/module";',
        'import midModule from "@/features/mid/module";',
        "",
        "export const authClientPlugins: never[] = [];",
        "export const clientModules = [alphaModule, zetaModule, midModule];",
        "",
      ].join("\n"),
    );
  });

  it("wzorzec spoza src/features na początku ścieżki nie tworzy modułu", async () => {
    const dir = await makeProject({
      alpha: { files: ["vendor/src/features/ghost/**"] },
    });
    await put(dir, "src/features/ghost/module.ts", "export default {};");
    await generate(dir);
    expect(await read(dir, "src/modules.generated.ts")).toContain(
      "export const modules: never[] = [];",
    );
  });
});

describe("generate: renderowanie regionów", () => {
  it("relacje trafiają do regionu pliku właściwego modelu, po jednej w linii", async () => {
    const dir = await makeProject({
      alpha: {
        schemaRelations: [
          { model: "User", field: "alphas Alpha[]" },
          { model: "Organization", field: "orgAlphas OrgAlpha[]" },
          { model: "User", field: "alphaLogs AlphaLog[]" },
        ],
      },
      beta: {
        schemaRelations: [{ model: "Organization", field: "betas Beta[]" }],
      },
    });
    await generate(dir);
    expect(await read(dir, "prisma/schema/auth.prisma")).toBe(
      "// wa:relations:start\n  alphas Alpha[]\n  alphaLogs AlphaLog[]\n// wa:relations:end\n",
    );
    expect(await read(dir, "prisma/schema/organizations.prisma")).toBe(
      "// wa:relations:start\n  orgAlphas OrgAlpha[]\n  betas Beta[]\n// wa:relations:end\n",
    );
  });

  it("env: sekcje modułów z env oddzielone pustą linią, moduł bez env bez nagłówka", async () => {
    const dir = await makeProject({
      alpha: {
        env: [
          { name: "ALPHA_ONE", example: "1" },
          { name: "ALPHA_TWO", example: "2" },
        ],
      },
      beta: { env: [{ name: "BETA_ONE", example: "b" }] },
      plain: {},
    });
    await generate(dir);
    expect(await read(dir, ".env.example")).toBe(
      "A=1\n# wa:modules:start\n# alpha\nALPHA_ONE=1\nALPHA_TWO=2\n\n# beta\nBETA_ONE=b\n# wa:modules:end\n",
    );
  });

  it("compose: puste linie bez wcięcia, końcowe znaki nowej linii obcięte, moduły w kolejnych liniach", async () => {
    const dir = await makeProject({
      alpha: { compose: "alpha.yml" },
      beta: { compose: "beta.yml" },
      plain: {},
    });
    await put(dir, "alpha.yml", "alpha:\n  image: a\n\n  ports: []\n\n\n");
    await put(dir, "beta.yml", "beta:\n  image: b\n");
    await generate(dir);
    expect(await read(dir, "docker-compose.yml")).toBe(
      "services:\n  # wa:services:start\n  alpha:\n    image: a\n\n    ports: []\n  beta:\n    image: b\n  # wa:services:end\n",
    );
  });

  it("brak pliku docelowego regionu nie przerywa generowania pozostałych", async () => {
    const dir = await makeProject({
      alpha: { env: [{ name: "A_X", example: "1" }] },
    });
    await rm(join(dir, ".env.example"));
    const { changed } = await generate(dir);
    expect(changed).not.toContain(".env.example");
  });

  it("nieczytelny plik docelowy (katalog zamiast pliku) → błąd, nie pominięcie", async () => {
    const dir = await makeProject({ alpha: {} });
    await rm(join(dir, ".env.example"));
    await mkdir(join(dir, ".env.example"));
    await expect(generate(dir)).rejects.toThrow();
  });
});
