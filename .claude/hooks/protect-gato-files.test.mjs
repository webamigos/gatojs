test("decide allows project and ejected files in every mode", () => {
  const target = { path: "src/shared/lib/audit.ts", module: "core" };
  for (const classification of ["project", "ejected"]) {
    for (const mode of ["warn", "block"]) {
      assert.deepEqual(
        decide(classification, mode, target),
        { action: "allow" },
        `${classification} ${mode}`,
      );
    }
  }
});

