const askOutput = (message) => ({
  systemMessage: message,
  hookSpecificOutput: {
    hookEventName: "PreToolUse",
    permissionDecision: "ask",
    permissionDecisionReason: message,
    additionalContext: message,
  },
});

const hookScript = fileURLToPath(
  new URL("./protect-gato-files.mjs", import.meta.url),
);

const writeFile = (root, relativePath, content) => {
  mkdirSync(dirname(join(root, relativePath)), { recursive: true });
  writeFileSync(join(root, relativePath), content);
};

const writeState = (project, kitState) =>
  writeFile(project, ".wa/kit.json", JSON.stringify(kitState, null, 2));

const withRoot = (run) => {
  const root = mkdtempSync(join(tmpdir(), "protect gato files "));
  try {
    run(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
};

const withProject = (kitState, run) =>
  withRoot((root) => {
    const project = join(root, "project");
    mkdirSync(join(project, ".git"), { recursive: true });
    if (kitState !== undefined) {
      writeState(project, kitState);
    }
    writeFile(project, "src/shared/lib/audit.ts", "import x from 'y';\n");
    writeFile(
      project,
      "src/features/audit-logs/services/track.ts",
      "export const track = 1;\n",
    );
    writeFile(project, "package.json", "{}\n");
    writeFile(project, "README.md", "# app\n");
    writeFile(
      project,
      "src/modules.generated.ts",
      `${GENERATED_HEAD}\nexport const modules = [];\n`,
    );
    writeFile(
      project,
      "src/features/invoices/module.ts",
      "export default {};\n",
    );
    run({ root, project });
  });

const envWithout = (name) =>
  Object.fromEntries(
    Object.entries(process.env).filter(([key]) => key !== name),
  );

const runHook = ({
  sessionDir,
  cwd,
  filePath,
  toolName = "Edit",
  spawnCwd = cwd,
}) =>
  spawnSync(process.execPath, [hookScript], {
    cwd: spawnCwd,
    input: JSON.stringify({
      tool_name: toolName,
      tool_input:
        toolName === "Write"
          ? { file_path: filePath, content: "export {};\n" }
          : { file_path: filePath, old_string: "a", new_string: "b" },
      cwd,
    }),
    env:
      sessionDir === undefined
        ? envWithout("CLAUDE_PROJECT_DIR")
        : { ...process.env, CLAUDE_PROJECT_DIR: sessionDir },
    timeout: 10_000,
  });

const runHookWithStdin = (stdin, cwd) =>
  spawnSync(process.execPath, [hookScript], {
    cwd,
    input: stdin,
    env: { ...process.env, CLAUDE_PROJECT_DIR: cwd },
    timeout: 10_000,
  });

const runInProject = (project, relativePath, toolName = "Edit") =>
  runHook({
    sessionDir: project,
    cwd: project,
    filePath: join(project, relativePath),
    toolName,
  });

const assertAllowedSilently = (result) => {
  assert.equal(result.status, 0);
  assert.equal(result.stdout.toString(), "");
  assert.equal(result.stderr.toString(), "");
};

const assertBlocked = (result, message) => {
  assert.equal(result.status, 2);
  assert.equal(result.stdout.toString(), "");
  assert.equal(result.stderr.toString(), `${message}\n`);
};

test("the protection mode is block", () => {
  assert.equal(PROTECTION_MODE, "block");
});

test("hookOutput allows with exit 0 and no output", () => {
  assert.deepEqual(hookOutput({ action: "allow" }), {
    status: 0,
    stdout: "",
    stderr: "",
  });
});

test("hookOutput asks with exit 0 and the ask object as one JSON object on stdout", () => {
  const output = hookOutput({ action: "ask", message: AUDIT_MESSAGE });
  assert.equal(output.status, 0);
  assert.equal(output.stderr, "");
  assert.deepEqual(JSON.parse(output.stdout), askOutput(AUDIT_MESSAGE));
  assert.deepEqual(JSON.parse(output.stdout), {
    systemMessage: AUDIT_MESSAGE,
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "ask",
      permissionDecisionReason: AUDIT_MESSAGE,
      additionalContext: AUDIT_MESSAGE,
    },
  });
  assert.equal(output.stdout.trim().startsWith("{"), true);
  assert.equal(output.stdout.trim().endsWith("}"), true);
  assert.equal(output.stdout.split("\n").filter(Boolean).length, 1);
});

test("hookOutput blocks with exit 2 and the message with a newline on stderr", () => {
  assert.deepEqual(hookOutput({ action: "block", message: AUDIT_MESSAGE }), {
    status: 2,
    stdout: "",
    stderr: `${AUDIT_MESSAGE}\n`,
  });
  assert.deepEqual(
    hookOutput({ action: "block", message: GENERATED_MESSAGE }),
    { status: 2, stdout: "", stderr: `${GENERATED_MESSAGE}\n` },
  );
});

